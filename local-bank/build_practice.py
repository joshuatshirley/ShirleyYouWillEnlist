"""Build local-bank/practice-data.js from local-bank/verified/*.json.

Usage: python -I build_practice.py
Validates every question (four choices, keyed answer, explanation, no
untranscribed image placeholders, unique ids) and refuses to write the
file if anything fails. Bump sw.js's CACHE_NAME afterwards on any installed
iPad, or the old bank keeps being served from cache.
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = {
    "AR": "Arithmetic Reasoning",
    "MK": "Mathematics Knowledge",
    "WK": "Word Knowledge",
    "PC": "Paragraph Comprehension",
}
KEEP = ("id", "source", "prompt", "choices", "correct", "explanation", "topic")


def main():
    # fixes.json: final decisions layered on the verified files -- items
    # excluded as ambiguous, and field patches for errors.
    fixes = json.load(open(os.path.join(HERE, "fixes.json"), encoding="utf-8"))
    sections = {code: [] for code in NAMES}
    errors = []
    seen_ids = set()
    excluded = 0
    for path in sorted(glob.glob(os.path.join(HERE, "verified", "*.json"))):
        for q in json.load(open(path, encoding="utf-8")):
            qid = q.get("id", "?")
            if qid in fixes["exclude"]:
                excluded += 1
                continue
            for k, v in fixes["patch"].get(qid, {}).items():
                if not k.startswith("_"):
                    q[k] = v
            if qid in seen_ids:
                errors.append("%s: duplicate id" % qid)
            seen_ids.add(qid)
            choices = q.get("choices") or {}
            if sorted(choices) != ["A", "B", "C", "D"] or not all(str(v).strip() for v in choices.values()):
                errors.append("%s: needs four non-empty choices" % qid)
            if q.get("correct") not in choices:
                errors.append("%s: correct answer not one of the choices" % qid)
            if not str(q.get("explanation", "")).strip() or not str(q.get("prompt", "")).strip():
                errors.append("%s: empty prompt or explanation" % qid)
            if "[[img:" in json.dumps(q, ensure_ascii=False):
                errors.append("%s: untranscribed image" % qid)
            if q.get("section") not in NAMES:
                errors.append("%s: unknown section" % qid)
                continue
            sections[q["section"]].append({k: q.get(k, "") for k in KEEP})
    if errors:
        print("NOT WRITTEN -- %d problem(s):" % len(errors))
        print("\n".join(errors))
        sys.exit(1)

    data = {"sections": {
        code: {"name": NAMES[code], "questions": qs} for code, qs in sections.items() if qs
    }}
    out = os.path.join(HERE, "practice-data.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by build_practice.py -- do not edit by hand.\n")
        f.write("// Licensed Barron's content: LOCAL USE ONLY, never commit or host.\n")
        f.write("window.__EST_PRACTICE__ = ")
        json.dump(data, f, ensure_ascii=False)
        f.write(";\n")
    for code, qs in sections.items():
        print("%s %d" % (code, len(qs)))
    print("excluded %d ambiguous item(s); wrote %s" % (excluded, out))


main()
